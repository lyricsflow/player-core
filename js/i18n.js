let currentLanguage = 'en-US';

export function detectBrowserLanguage() {
  const browserLang = navigator.language || navigator.userLanguage || 'en-US';
  if (TRANSLATIONS[browserLang]) return browserLang;

  const prefix = browserLang.split('-')[0].toLowerCase();
  const match = SUPPORTED_LANGUAGES.find(l => l.code.toLowerCase().startsWith(prefix));
  return match ? match.code : 'en-US';
}

export function getCurrentLang() {
  return currentLanguage;
}

export function setLanguage(langCode) {
  if (!TRANSLATIONS[langCode]) {
    langCode = 'en-US';
  }
  currentLanguage = langCode;
  localStorage.setItem('lyricsflow_app_lang', langCode);

  const langObj = SUPPORTED_LANGUAGES.find(l => l.code === langCode);
  const isPlayerPage = typeof window !== 'undefined' && (
    (window.location && window.location.pathname && window.location.pathname.includes('player.html')) ||
    document.getElementById('LyricsflowPage') !== null
  );
  const dir = isPlayerPage ? 'ltr' : (langObj?.dir || 'ltr');

  document.documentElement.lang = langCode;
  document.documentElement.dir = dir;
  document.documentElement.setAttribute('dir', dir);
  if (isPlayerPage && document.body) {
    document.body.setAttribute('dir', 'ltr');
  }
  document.documentElement.setAttribute('data-lang', langCode);

  applyDOMTranslations();
  window.dispatchEvent(new CustomEvent('lyricsflow-lang-changed', { detail: { lang: langCode, dir } }));
}

function escapeRegExp(string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

export function t(key, vars = {}) {
  const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS['en-US'];
  let text = dict[key] || TRANSLATIONS['en-US'][key] || key;

  if (typeof text === 'string' && vars) {
    Object.keys(vars).forEach(k => {
      text = text.replace(new RegExp(`\\{${escapeRegExp(k)}\\}`, 'g'), vars[k]);
    });
  }
  return text;
}

export function formatLocalizedDate(dateInput, lang = null) {
  if (!dateInput) return '';
  const currentLang = lang || getCurrentLang();
  const date = (typeof dateInput === 'string' || typeof dateInput === 'number') ? new Date(dateInput) : dateInput;
  if (isNaN(date.getTime())) return String(dateInput);

  const localeMap = {
    'en-US': 'en-US',
    'ar': 'ar-SA',
    'es-ES': 'es-ES',
    'es-MX': 'es-MX',
    'pt-BR': 'pt-BR',
    'zh-Hans': 'zh-CN',
    'ja': 'ja-JP',
    'ko': 'ko-KR',
    'de': 'de-DE',
    'fr': 'fr-FR'
  };

  const loc = localeMap[currentLang] || 'en-US';
  try {
    return new Intl.DateTimeFormat(loc, {
      year: 'numeric',
      month: 'long',
      day: 'numeric'
    }).format(date);
  } catch (e) {
    return date.toLocaleDateString(loc);
  }
}

export function formatLocalizedYear(dateInput, lang = null) {
  if (!dateInput) return '';
  const date = (typeof dateInput === 'string' || typeof dateInput === 'number') ? new Date(dateInput) : dateInput;
  if (isNaN(date.getTime())) return String(dateInput);
  return date.getFullYear().toString();
}

export function applyDOMTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.setAttribute('placeholder', t(key));
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.setAttribute('title', t(key));
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria-label');
    if (key) el.setAttribute('aria-label', t(key));
  });
}

const initLanguage = () => {
  const saved = localStorage.getItem('lyricsflow_app_lang') || detectBrowserLanguage();
  setLanguage(saved);
};

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initLanguage);
} else {
  initLanguage();
}
